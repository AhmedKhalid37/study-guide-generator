# Stage 3 — export ZIP portability (FastAPI-skippable)
# ---------------------------------------------------------------------------
def stage_export() -> None:
    """Stitch: real Job -> pilot-produced clean.md -> export bundle carries one PNG.

    Verifications 9–12. Drives the real ``api.server.export_bundle`` against temp-dir
    Jobs (``_get_job`` monkeypatched), mirroring test_visual_pilot_export_asset.py.
    SKIPPED when FastAPI is not importable in host Python (run in Docker).
    """
    try:
        from fastapi import HTTPException

        from api import server  # noqa: WPS433
    except Exception as exc:
        skip("export.bundle", f"FastAPI unavailable ({type(exc).__name__})")
        return

    from pipeline.job_manager import Job

    EXTRA = "fig_p007_09_extra.png"

    def _make_job(root: Path, job_id: str, *, with_pdf: bool, clean_md: str,
                  assets: dict[str, bytes] | None) -> Job:
        job = Job(id=job_id, root=root)
        job.input_dir.mkdir(parents=True, exist_ok=True)
        job.logs_dir.mkdir(parents=True, exist_ok=True)
        # Opt the job in via the persisted manifest (the real per-job switch).
        job._write_manifest({
            "id": job.id, "status": "completed", "title": job.id,
            "visual_markdown_image_pilot": True,
        })
        if with_pdf:
            job.final_pdf.write_bytes(b"%PDF-1.4 synthetic pdf bytes")
        if assets:
            job.assets_dir.mkdir(parents=True, exist_ok=True)
            for name, data in assets.items():
                (job.assets_dir / name).write_bytes(data)
        job.save_text(job.clean_md, clean_md)
        return job

    def _bundle(jobs_by_id, job_ids, artifacts):
        original = server._get_job

        def fake_get_job(raw_id):
            jid = str(raw_id)
            if jid in jobs_by_id:
                return jobs_by_id[jid]
            raise HTTPException(status_code=404, detail="Job not found.")

        server._get_job = fake_get_job
        try:
            return server.export_bundle(
                server.BundleRequest(job_ids=job_ids, artifacts=artifacts)
            )
        finally:
            server._get_job = original

    # Produce clean.md through the genuine pilot so the export consumes a real chain.
    old = _force_env("1")
    try:
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            seed = _make_job(
                root, "job-seed", with_pdf=True,
                clean_md=BASE_MD,
                assets={ASSET: PNG_BYTES},
            )
            # Stitch: regenerate clean.md via the pilot against this real Job.
            seed_manifest = seed.assets_dir.parent / "visual_assets_manifest.json"
            seed_manifest.write_text(
                json.dumps(_manifest([_figure_asset(SLUG, image_ref=ASSET_REF)])) + "\n",
                encoding="utf-8",
            )
            produced, info = vmi.apply_visual_markdown_pilot(seed, BASE_MD)
            record(produced)
            check("export.pilot_produced_image",
                  info.get("status") == vmi.STATUS_INSERTED and ASSET_REF in produced, str(info))
            seed.save_clean_md(produced, source="slice58_e2e")

            # Add an unreferenced extra crop alongside the referenced one.
            (seed.assets_dir / EXTRA).write_bytes(PNG_BYTES)

            resp = _bundle({"job-seed": seed}, ["job-seed"], ["pdf", "markdown"])
            with zipfile.ZipFile(io.BytesIO(resp.body)) as zf:
                names = zf.namelist()
                png_entries = [n for n in names if n.lower().endswith(".png")]
                manifest_text = record(zf.read("manifest.json").decode("utf-8"))
                png_data = zf.read(png_entries[0]) if png_entries else b""

            # (9) exactly the single referenced PNG, under the job's assets/ folder.
            check("export.exactly_one_png", len(png_entries) == 1, str(png_entries))
            check("export.png_is_referenced_asset",
                  any(n.endswith(f"/assets/{ASSET}") for n in names), str(names))
            check("export.png_under_assets_relative",
                  all("/assets/" in p and not p.startswith("/") and ".." not in p
                      and "\\" not in p for p in png_entries), str(png_entries))
            check("export.png_carries_real_bytes", png_data == PNG_BYTES)

            # (10) the unreferenced extra crop / whole assets dir are NOT bundled.
            check("export.extra_crop_excluded",
                  not any(n.endswith(f"/assets/{EXTRA}") for n in names), str(names))
            check("export.no_blanket_assets_dir", len(png_entries) <= 1, str(png_entries))

            # (12) bundle index records only the safe relative ref; no bytes/paths.
            manifest = json.loads(manifest_text)
            entry = manifest["jobs"][0]
            check("export.manifest_safe_relative_ref",
                  entry.get("visual_pilot_asset") == ASSET_REF,
                  str(entry.get("visual_pilot_asset")))
            check("export.manifest_no_image_bytes", PNG_BODY_SENTINEL not in manifest_text)
            check("export.manifest_no_leak", _sweep_one(manifest_text) is None,
                  _sweep_one(manifest_text) or "")

            # (11a) the ride-along PNG does NOT inflate the requested-artifact count.
            check("export.files_included_requested_only",
                  manifest.get("files_included") == 2, str(manifest.get("files_included")))

        # (11b) a pilot-PNG-only job with the requested artifact absent still 404s —
        # the PNG can never satisfy the requested-artifact gate by itself.
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            gate_job = _make_job(
                root, "job-gate", with_pdf=False,
                clean_md=produced,
                assets={ASSET: PNG_BYTES},
            )
            raised = False
            try:
                _bundle({"job-gate": gate_job}, ["job-gate"], ["pdf"])
            except HTTPException as exc:
                raised = exc.status_code == 404
            check("export.png_alone_does_not_satisfy_gate", raised)
    finally:
        _restore_env(old)


# ---------------------------------------------------------------------------
# Stage 4 — no-leak sweep over every serialized output (verification 13)
# ---------------------------------------------------------------------------
def _sweep_one(text: str) -> str | None:
    for label, pat in _LEAK_PATTERNS:
        if pat.search(text):
            return label
    return None


def stage_leak_sweep() -> None:
    leaks: list[str] = []
    for blob in OUTPUTS:
        found = _sweep_one(blob)
        if found is not None:
            leaks.append(found)
    check("sweep.no_leaks_in_any_output", not leaks, ",".join(sorted(set(leaks))))
    check("sweep.had_outputs_to_scan", len(OUTPUTS) > 0, str(len(OUTPUTS)))


def main() -> int:
    with tempfile.TemporaryDirectory() as d:
        work = Path(d)
        stage_insertion(work)
        stage_render(work)
    stage_export()
    stage_leak_sweep()
    print(f"\n{PASS} passed, {FAIL} failed, {SKIP} skipped")
    return 1 if FAIL else 0


if __name__ == "__main__":
    raise SystemExit(main())
