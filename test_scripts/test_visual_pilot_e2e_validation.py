# Stage 2 — render compatibility (HTML always-ish; PDF/DOCX host-skippable)
# ---------------------------------------------------------------------------
def stage_render(work: Path) -> None:
    """Stitch: the pilot's clean.md renders to HTML/PDF/DOCX with the relative ref.

    Verifications 6–8. Renderers are NOT rewritten; missing host deps SKIP cleanly.
    """
    clean = work / "clean.md"

    # (6) HTML contains a safe relative <img src="assets/...png"> and no absolute path.
    try:
        from pipeline.html_renderer import render_markdown_file
    except Exception as exc:  # markdown-it / deps unavailable
        skip("render.html", f"renderer import unavailable ({type(exc).__name__})")
    else:
        try:
            html = record(render_markdown_file(clean))
        except Exception as exc:
            skip("render.html", f"render unavailable ({type(exc).__name__})")
        else:
            check("render.html_has_relative_img",
                  "<img" in html and f'src="{ASSET_REF}"' in html, html[:200])
            check("render.html_no_absolute_path",
                  "file://" not in html and "/home/" not in html and "/etc/" not in html)

    # (7) PDF render completes and produces a non-empty PDF; SKIP if no Chromium.
    try:
        from pipeline.pdf_renderer import render_pdf, _find_chromium
    except Exception as exc:
        skip("render.pdf", f"renderer import unavailable ({type(exc).__name__})")
    else:
        if _find_chromium() is None:
            skip("render.pdf", "no Chromium on host")
        else:
            out_pdf = work / "final.pdf"
            try:
                render_pdf(clean, out_pdf)
            except Exception as exc:
                check("render.pdf_no_raise", False, type(exc).__name__)
            else:
                check("render.pdf_nonempty", out_pdf.is_file() and out_pdf.stat().st_size > 0)
                # Slice 60: a non-empty PDF is not enough — confirm the figure is an
                # embedded image object, not a broken/alt-text-only marker. SKIP only
                # when PyMuPDF is unavailable on the host.
                try:
                    import fitz  # PyMuPDF
                except Exception as exc:
                    skip("render.pdf_image_visible", f"PyMuPDF unavailable ({type(exc).__name__})")
                else:
                    embedded = False
                    try:
                        with fitz.open(str(out_pdf)) as doc:
                            embedded = any(page.get_images(full=True) for page in doc)
                    except Exception as exc:
                        skip("render.pdf_image_visible", f"inspect unavailable ({type(exc).__name__})")
                    else:
                        check("render.pdf_image_visible", embedded)

    # (8) DOCX generation embeds or degrades without raising; SKIP if python-docx absent.
    try:
        import docx  # noqa: F401
        from pipeline.docx_renderer import render_docx
    except Exception as exc:
        skip("render.docx", f"python-docx unavailable ({type(exc).__name__})")
    else:
        out_docx = work / "final.docx"
        try:
            render_docx(clean, out_docx, title="Synthetic Guide")
        except Exception as exc:
            check("render.docx_no_raise", False, type(exc).__name__)
        else:
            check("render.docx_nonempty", out_docx.is_file() and out_docx.stat().st_size > 0)


